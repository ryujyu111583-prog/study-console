/** 横に並んだ同じ色をまとめて、SVG の rect の数を減らす */
export function artRuns(rows: string[]) {
  const out: { x: number; y: number; w: number; c: string }[] = [];
  const top = ART_SIZE - rows.length;
  rows.forEach((row, ry) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== "." && ART_PALETTE[ch]) out.push({ x, y: ry + top, w: Math.min(end, ART_SIZE) - x, c: ART_PALETTE[ch] });
      x = end;
    }
  });
  return out;
}
